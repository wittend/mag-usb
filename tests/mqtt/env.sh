# Shared settings for the local MQTT test broker.  Sourced by the other scripts
# in this directory; not run directly.

MQTT_TEST_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MQTT_RUN_DIR="$MQTT_TEST_DIR/run"

# Test ports, chosen so they don't clash with a system Mosquitto on 1883.
MQTT_PORT_PLAIN=18830   # plain TCP, used by the admin tool and the ACL tests
MQTT_PORT_TLS=18834     # TLS, certificate from the test CA
MQTT_PORT_WS=19001      # MQTT over WebSocket, for the dashboard

# The dynsec plugin.  Set MQTT_DYNSEC_PLUGIN to override the search.
if [ -z "${MQTT_DYNSEC_PLUGIN:-}" ]; then
    MQTT_DYNSEC_PLUGIN="$(find /usr/lib /usr/local/lib -name mosquitto_dynamic_security.so 2>/dev/null | head -n 1)"
fi

